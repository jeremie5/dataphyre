function validId(value,maximum=127){return typeof value==='string'&&value.length>0&&value.length<=maximum&&/^[a-z][a-z0-9_.-]*$/.test(value);}

function secureTarget(value){
	assert(typeof value==='string'&&value.length>0&&value.length<=2048,'Browser target must be bounded text.');
	assert(!/[\u0000-\u0020\u007f\\]/.test(value)&&!value.startsWith('#')&&!value.startsWith('//'),'Browser target contains an ambiguous or unsafe URL form.');
	if(value.startsWith('/')){return value;}
	let parsed;try{parsed=new URL(value);}catch(error){throw new Error('Browser target must be root-relative or absolute HTTP(S).');}
	assert(['http:','https:'].includes(parsed.protocol)&&!parsed.username&&!parsed.password,'Browser target must use credential-free HTTP(S).');
	return parsed.toString();
}

function validateManifest(manifest){
	assert(manifest&&manifest.type==='panel_inclusive_quality_matrix','Manifest type must be panel_inclusive_quality_matrix.');
	assert(manifest.version===1,'Manifest version must be 1.');
	assert(typeof manifest.digest==='string'&&/^[a-f0-9]{64}$/.test(manifest.digest),'Manifest requires a SHA-256 digest.');
	assert(validId(manifest.name,64),'Manifest requires a stable bounded name.');
	secureTarget(manifest.url);
	assert(Array.isArray(manifest.profiles)&&manifest.profiles.length>0&&manifest.profiles.length<=32,'Manifest locale profiles exceed their bounds.');
	assert(Array.isArray(manifest.contracts)&&manifest.contracts.length>0&&manifest.contracts.length<=64,'Manifest contracts exceed their bounds.');
	assert(Number.isInteger(manifest.case_count)&&manifest.case_count>0&&manifest.case_count<=2048,'Manifest case count exceeds its bounds.');
	assert(Array.isArray(manifest.browser_manifests)&&manifest.browser_manifests.length>0&&manifest.browser_manifests.length<=manifest.case_count,'Manifest has no browser cases or exceeds its case count.');
	const profileIds=new Set();for(const profile of manifest.profiles){assert(profile&&validId(profile.id)&&!profileIds.has(profile.id),'Manifest locale profile ids must be unique and stable.');profileIds.add(profile.id);}
	const contractIds=new Set();for(const contract of manifest.contracts){assert(contract&&validId(contract.id)&&!contractIds.has(contract.id),'Manifest contract ids must be unique and stable.');contractIds.add(contract.id);}
	const caseIds=new Set();
	for(const item of manifest.browser_manifests){
		assert(item&&item.type==='panel_browser_regression_manifest'&&item.version===1,'Browser manifest has an unsupported type or version.');
		assert(validId(item.name,383)&&!caseIds.has(item.name),'Browser manifest case ids must be unique and stable.');caseIds.add(item.name);
		secureTarget(item.url);
		assert(Array.isArray(item.interactions)&&item.interactions.length<=32,'Browser manifest interactions exceed their bounds.');
		assert(item.meta?.quality_case_id===item.name,'Browser manifest case identity mismatch.');
		assert(item.meta?.quality_matrix_digest===manifest.digest,'Browser manifest matrix digest mismatch.');
		assert(item.meta?.quality_contract?.execution==='browser','Non-browser contract leaked into browser manifests.');
		assert(profileIds.has(item.meta?.quality_profile?.id),'Browser manifest references an unknown locale profile.');
		assert(contractIds.has(item.meta?.quality_contract?.id),'Browser manifest references an unknown contract.');
		if(item.meta?.quality_contract?.domain==='assistive_technology'){
			assert(item.meta.quality_contract.automation==='automated_proxy'&&Array.isArray(item.meta.quality_contract.does_not_prove)&&item.meta.quality_contract.does_not_prove.length>0,'Browser assistive-technology contracts must be bounded proxies.');
		}
	}
	return manifest;
}

function validateWithPhp(config,manifestPath,manifest){
	const result=spawnSync(config.php,[path.join(cwd,'dev','tools','panel_developer.php'),'inclusive-quality-validate','--matrix='+manifestPath],{cwd,encoding:'utf8',maxBuffer:MAX_JSON_BYTES,shell:false,windowsHide:true});
	assert(!result.error&&result.status===0,'PHP rejected the inclusive-quality matrix: '+String(result.stderr||result.error||result.stdout).slice(-2000));
	let validation;try{validation=JSON.parse(String(result.stdout||''));}catch(error){throw new Error('PHP matrix validator returned invalid JSON.');}
	authenticateBrowserCases(manifest,validation);
}

function authenticateBrowserCases(manifest,validation){
	assert(validation&&validation.type==='panel_inclusive_quality_validation'&&validation.version===1&&validation.valid===true,'PHP matrix validator returned an unsupported validation envelope.');
	assert(validation.name===manifest.name&&validation.digest===manifest.digest&&validation.case_count===manifest.case_count&&validation.browser_case_count===manifest.browser_manifests.length,'PHP matrix validator did not authenticate the manifest identity, digest, and counts.');
	assert(Array.isArray(validation.browser_cases)&&validation.browser_cases.length===manifest.browser_manifests.length,'PHP matrix validator did not return the canonical browser case set.');
	const profiles=new Map(manifest.profiles.map(item=>[item.id,item]));const contracts=new Map(manifest.contracts.map(item=>[item.id,item]));
	const canonical=new Map();
	for(const item of validation.browser_cases){
		assert(item&&validId(item.case_id,383)&&validId(item.profile_id)&&validId(item.contract_id),'PHP matrix validator returned an invalid browser case mapping.');
		assert(profiles.has(item.profile_id)&&contracts.has(item.contract_id),'PHP matrix validator returned unknown canonical case ids.');
		assert(!canonical.has(item.case_id),'PHP matrix validator returned duplicate browser case ids.');
		canonical.set(item.case_id,{profile_id:item.profile_id,contract_id:item.contract_id,url:secureTarget(item.url),profile:profiles.get(item.profile_id),contract:contracts.get(item.contract_id)});
	}
	for(const item of manifest.browser_manifests){
		const expected=canonical.get(item.name);
		assert(expected,'Browser manifest case set differs from the PHP-authenticated matrix.');
		assert(item.meta?.quality_profile?.id===expected.profile_id&&item.meta?.quality_contract?.id===expected.contract_id&&secureTarget(item.url)===expected.url&&canonicalJson(item.meta.quality_profile)===canonicalJson(expected.profile)&&canonicalJson(item.meta.quality_contract)===canonicalJson(expected.contract),'Browser manifest case mapping differs from the PHP-authenticated matrix.');
		canonical.delete(item.name);
	}
	assert(canonical.size===0,'Browser manifest omitted PHP-authenticated cases.');
	return manifest;
}

function canonicalJson(value){
	const normalize=item=>Array.isArray(item)?item.map(normalize):(item&&typeof item==='object'?Object.keys(item).sort().reduce((out,key)=>{out[key]=normalize(item[key]);return out;},{}):item);
	return JSON.stringify(normalize(value));
}

