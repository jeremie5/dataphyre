function parseArgs(argv){
	const parsed={allowNoSandbox:false,allowOrigins:[],baseUrl:'',browser:'',capabilities:'',contracts:[],headed:false,help:false,list:false,manifest:'',php:process.env.PHP_BINARY||'php',profiles:[],report:'',reportOnly:false};
	for(let index=0;index<argv.length;index++){
		const argument=String(argv[index]);
		const value=()=>{const equals=argument.indexOf('=');if(equals!==-1){return argument.slice(equals+1);}index++;return String(argv[index]||'');};
		if(argument==='--help'||argument==='-h'){parsed.help=true;}
		else if(argument==='--headed'){parsed.headed=true;}
		else if(argument==='--list'){parsed.list=true;}
		else if(argument==='--report-only'){parsed.reportOnly=true;}
		else if(argument==='--allow-no-sandbox'){parsed.allowNoSandbox=true;}
		else if(argument==='--base-url'||argument.startsWith('--base-url=')){parsed.baseUrl=value();}
		else if(argument==='--browser'||argument.startsWith('--browser=')){parsed.browser=value();}
		else if(argument==='--manifest'||argument.startsWith('--manifest=')){parsed.manifest=value();}
		else if(argument==='--report'||argument.startsWith('--report=')){parsed.report=value();}
		else if(argument==='--capabilities'||argument.startsWith('--capabilities=')){parsed.capabilities=value();}
		else if(argument==='--php'||argument.startsWith('--php=')){parsed.php=value();}
		else if(argument==='--allow-origin'||argument.startsWith('--allow-origin=')){parsed.allowOrigins.push(...split(value()));}
		else if(argument==='--contract'||argument.startsWith('--contract=')){parsed.contracts.push(...split(value()));}
		else if(argument==='--profile'||argument.startsWith('--profile=')){parsed.profiles.push(...split(value()));}
		else {throw new Error('Unknown argument: '+argument);}
	}
	parsed.contracts=Array.from(new Set(parsed.contracts));
	parsed.profiles=Array.from(new Set(parsed.profiles));
	parsed.allowOrigins=Array.from(new Set(parsed.allowOrigins));
	return parsed;
}

