function missingCapabilities(contract,capabilities){return(contract.required_capabilities||[]).filter(id=>capabilities[id]?.status!=='available'||capabilities[id]?.execution!=='browser');}

async function executeCase(browser,item,baseUrl,extraOrigins,capabilities,reportPath,browserVersion){
	const profile=item.meta.quality_profile;const contract=item.meta.quality_contract;const page=await browser.newPage();const started=Date.now();let status='passed';let assertions=0;let notes=null;let navigationPolicy=null;
	try{
		await prepareEnvironment(page,profile,contract,capabilities);
		const target=targetUrl(item,baseUrl,extraOrigins);navigationPolicy=await installMainFrameNavigationPolicy(page,baseUrl,extraOrigins);
		let response;
		try{response=await page.goto(target,{waitUntil:'domcontentloaded',timeout:30000});}
		catch(error){if(navigationPolicy.blocked.length){throw new Error('Blocked non-allowlisted main-frame navigation before contact: '+navigationPolicy.blocked.join(', '));}throw error;}
		assert(navigationPolicy.blocked.length===0,'Blocked non-allowlisted main-frame navigation before contact.');
		assert(response&&response.ok(),'Panel target returned HTTP '+String(response?.status()||'no response')+'.');
		assert(navigationAllowed(response.url(),baseUrl,extraOrigins),'Panel target redirected to a non-allowlisted origin.');
		await applyPageEnvironment(page,profile);
		const unavailable=missingCapabilities(contract,capabilities);
		if(unavailable.length){status='blocked';notes='Unavailable capabilities: '+unavailable.join(', ');}
		else{const probe=probes[contract.id];assert(typeof probe==='function','No browser probe implements contract '+contract.id+'.');assertions=await probe(page,profile,contract);assert(Number.isInteger(assertions)&&assertions>0,'Probe returned no assertions.');}
	}catch(error){status='failed';notes=String(error?.stack||error).slice(0,2000);assertions=Math.max(assertions,1);}
	finally{if(navigationPolicy){await navigationPolicy.dispose();}await page.close();}
	const executed=status==='passed'||status==='failed';
	return{case_id:item.name,status,execution:'browser',executor:executed?'Chromium '+browserVersion:null,artifact:executed?reportPath:null,assertions:executed?assertions:0,duration_ms:executed?Date.now()-started:0,capabilities:executed?Array.from(new Set(contract.required_capabilities||[])).sort():[],notes,observed_at:executed?new Date().toISOString():null,matrix_digest:item.meta.quality_matrix_digest};
}

async function run(config){
	const manifestPath=absolute(config.manifest);const manifest=validateManifest(readJson(manifestPath));validateWithPhp(config,manifestPath,manifest);const cases=selectCases(manifest,config.contracts,config.profiles);
	assert(cases.length>0,'No browser cases matched the requested selection.');
	if(config.list){for(const item of cases){console.log(item.name);}return{exitCode:0};}
	assert(config.report,'--report is required for an executed browser run.');
	allowedOrigins(config.baseUrl,config.allowOrigins);
	const reportPath=absolute(config.report);const puppeteer=findPuppeteer();const launchArguments=['--disable-dev-shm-usage'];if(config.allowNoSandbox){launchArguments.push('--no-sandbox');}const browser=await puppeteer.launch({executablePath:findBrowser(config.browser),headless:!config.headed,args:launchArguments});
	let browserVersion='unknown';let capabilities={};const evidence=[];
	try{browserVersion=await browser.version();capabilities=baseCapabilities(browserVersion);for(const item of cases){evidence.push(await executeCase(browser,item,config.baseUrl,config.allowOrigins,capabilities,reportPath,browserVersion));}}
	finally{await browser.close();}
	const failed=evidence.filter(item=>item.status==='failed');const blocked=evidence.filter(item=>item.status==='blocked');const passed=evidence.filter(item=>item.status==='passed');
	const capabilityPayload={type:'panel_quality_capability_report',version:1,capabilities};
	const report={type:'panel_inclusive_quality_browser_report',version:1,matrix:{name:manifest.name,digest:manifest.digest},browser:browserVersion,ok:failed.length===0&&blocked.length===0,security:{sandbox_disabled:config.allowNoSandbox,allowed_origins:Array.from(allowedOrigins(config.baseUrl,config.allowOrigins)).sort(),main_frame_navigation_policy:'pre_request_same_origin_allowlist',subresource_origin_policy:'page_policy_not_enforced'},selection:{contracts:config.contracts,profiles:config.profiles},summary:{total:evidence.length,passed:passed.length,failed:failed.length,blocked:blocked.length},capabilities:capabilityPayload,evidence};
	writeJsonAtomic(reportPath,report);if(config.capabilities){writeJsonAtomic(absolute(config.capabilities),capabilityPayload);}
	console.log(JSON.stringify({report:reportPath,ok:report.ok,...report.summary}));
	return{exitCode:report.ok||config.reportOnly?0:1,report};
}

async function main(){const args=parseArgs(process.argv.slice(2));if(args.help){printHelp();return 0;}assert(args.manifest,'--manifest is required.');const result=await run(args);return result.exitCode;}

if(require.main===module){main().then(code=>{process.exitCode=code;}).catch(error=>{console.error(error?.stack||String(error));process.exitCode=2;});}

