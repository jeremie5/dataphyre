/**
 * Evaluates a single dependency condition against a submitted value.
 *
 * Array expectations model membership checks, boolean expectations use HTML
 * form truth semantics, and scalar expectations compare by string value to
 * align with submitted form payloads.
 *
 * @param {*} actual Current submitted value.
 * @param {*} expected Expected condition value from field metadata.
 * @returns {boolean} Whether the dependency condition matches.
 */
function dpPanelConditionMatches(actual,expected){
	if(Array.isArray(expected)){
		return expected.map(String).indexOf(String(actual))!==-1;
	}
	if(expected===true){
		return !!actual&&actual!=="0"&&actual!=="false";
	}
	if(expected===false){
		return !actual||actual==="0"||actual==="false";
	}
	return String(actual)===String(expected);
}
/**
 * Evaluates a dependency map using `when` or `unless` mode.
 *
 * @param {Object<string, *>} conditions Field-name to expected-value map.
 * @param {string} mode Dependency mode, either `when` or `unless`.
 * @returns {boolean} Whether all conditions pass for the requested mode.
 */
function dpPanelConditionsMatch(conditions,mode){
	var matched=true;
	Object.keys(conditions).forEach(function(name){
		var hit=dpPanelConditionMatches(dpPanelFieldValue(name),conditions[name]);
		if(mode==="unless"){hit=!hit;}
		if(!hit){matched=false;}
	});
	return matched;
}
/**
 * Returns the interactive controls owned by a Panel field wrapper.
 *
 * @param {Element} field Field wrapper element.
 * @returns {NodeListOf<Element>} Input, select, and textarea controls.
 */
function dpPanelFieldControls(field){
	return field.querySelectorAll("input,select,textarea");
}
/**
 * Applies native required validation only to submitted field controls.
 *
 * @param {HTMLInputElement|HTMLSelectElement|HTMLTextAreaElement} input Control to update.
 * @param {boolean} required Whether the owning field is visible and required.
 * @returns {void}
 */
function dpPanelSetFieldControlRequired(input,required){
	var name=typeof input.name==="string" ? input.name.trim() : "";
	var searchableAuxiliary=!!(input.hasAttribute&&input.hasAttribute("data-dp-panel-searchable-select-input"));
	var participates=input.type!=="hidden"&&name!==""&&!searchableAuxiliary;
	input.required=participates&&required;
	input.setAttribute("aria-required",participates&&required ? "true" : "false");
}
/**
 * Recomputes client-side field visibility and required state from dependencies.
 *
 * The function mutates only DOM state: field visibility classes, disabled flags,
 * `required`, and ARIA metadata. Server validation remains authoritative, but
 * this keeps the browser experience aligned with the same dependency contract.
 *
 * @returns {void}
 */
function dpPanelRefreshDependencies(){
	document.querySelectorAll("[data-dp-panel-visible-when],[data-dp-panel-hidden-when],[data-dp-panel-required-when],[data-dp-panel-required-unless]").forEach(function(field){
		var visible=true;
		var visibleWhen=dpPanelParseDependency(field.dataset.dpPanelVisibleWhen);
		var hiddenWhen=dpPanelParseDependency(field.dataset.dpPanelHiddenWhen);
		var requiredWhen=dpPanelParseDependency(field.dataset.dpPanelRequiredWhen);
		var requiredUnless=dpPanelParseDependency(field.dataset.dpPanelRequiredUnless);
		if(Object.keys(visibleWhen).length&&!dpPanelConditionsMatch(visibleWhen,"when")){
			visible=false;
		}
		if(Object.keys(hiddenWhen).length&&dpPanelConditionsMatch(hiddenWhen,"when")){
			visible=false;
		}
		var required=Object.keys(requiredWhen).length&&dpPanelConditionsMatch(requiredWhen,"when");
		if(Object.keys(requiredUnless).length){
			required=required||dpPanelConditionsMatch(requiredUnless,"unless");
		}
		field.classList.toggle("dp-panel-field-hidden",!visible);
		field.classList.toggle("dp-panel-field-required",required);
		dpPanelFieldControls(field).forEach(function(input){
			input.disabled=!visible;
			dpPanelSetFieldControlRequired(input,visible&&required);
		});
	});
}
var dpPanelReactiveTimers={};
/**
 * Normalizes a form control name into the base Panel field name.
 *
 * @param {HTMLInputElement|HTMLSelectElement|HTMLTextAreaElement} input Source control.
 * @returns {string} Field name without array suffixes or nested bracket paths.
 */
function dpPanelReactiveFieldName(input){
	var name=(input&&input.name)||"";
	if(!name){return "";}
	return name.replace(/\[\]$/,"").split("[")[0];
}
/**
 * Escapes a value for use in a CSS selector.
 *
 * The native `CSS.escape` implementation is preferred when available; the
 * fallback only covers the quote and slash characters used by generated field
 * selectors in this runtime.
 *
 * @param {string} value Raw selector value.
 * @returns {string} Escaped selector fragment.
 */
function dpPanelCssEscape(value){
	if(window.CSS&&typeof CSS.escape==="function"){return CSS.escape(value);}
	return String(value).replace(/["\\]/g,"\\$&");
}
/**
 * Checks whether a reactive field depends on a source field.
 *
 * @param {Element} field Candidate dependent field wrapper.
 * @param {string} name Source field name.
 * @returns {boolean} Whether the field should refresh after the source changes.
 */
function dpPanelReactiveDependsOn(field,name){
	if(!name){return true;}
	var depends=dpPanelParseDependency(field.dataset.dpPanelDependsOn);
	if(Array.isArray(depends)){return depends.map(String).indexOf(String(name))!==-1;}
	if(depends&&typeof depends==="object"){return Object.keys(depends).indexOf(String(name))!==-1;}
	return false;
}
/**
 * Resolves the endpoint used for reactive field requests.
 *
 * @param {HTMLFormElement} form Panel form carrying optional reactive URL metadata.
 * @returns {URL} Absolute URL for same-origin reactive POST requests.
 */
function dpPanelReactiveUrl(form){
	var raw=form.dataset.dpPanelReactiveUrl||window.location.href;
	return new URL(raw,window.location.href);
}
/**
 * Collects fields whose state may change after a source control update.
 *
 * The target set includes dynamic options, server-side state updates, explicit
 * dependencies, and optionally the source field itself for validation refreshes.
 *
 * @param {HTMLFormElement} form Panel form containing field wrappers.
 * @param {string} sourceName Normalized source field name.
 * @param {boolean} includeSource Whether to include the source field in the target set.
 * @returns {Element[]} Field wrappers eligible for reactive state refresh.
 */
function dpPanelReactiveStateTargets(form,sourceName,includeSource){
	return Array.prototype.slice.call(form.querySelectorAll("[data-dp-panel-field-name]")).filter(function(field){
		var fieldName=field.dataset.dpPanelFieldName||"";
		if(includeSource&&fieldName===sourceName){return true;}
		if(field.dataset.dpPanelDynamicOptions==="1"&&dpPanelReactiveDependsOn(field,sourceName)){return true;}
		if(field.dataset.dpPanelStateUpdates==="1"&&(fieldName===sourceName||dpPanelReactiveDependsOn(field,sourceName))){return true;}
		return (field.hasAttribute("data-dp-panel-visible-when")||field.hasAttribute("data-dp-panel-hidden-when")||field.hasAttribute("data-dp-panel-required-when")||field.hasAttribute("data-dp-panel-required-unless"))&&dpPanelReactiveDependsOn(field,sourceName);
	});
}
/**
 * Applies validation messages to a field wrapper.
 *
 * Existing generated errors are removed before new errors are appended, and ARIA
 * invalid state is synchronized across every control in the field.
 *
 * @param {Element} field Field wrapper.
 * @param {string[]} errors Validation messages returned by the server.
 * @returns {void}
 */
function dpPanelApplyFieldErrors(field,errors){
	field.querySelectorAll(":scope > .dp-panel-error").forEach(function(error){error.remove();});
	field.classList.toggle("dp-panel-field-invalid",Array.isArray(errors)&&errors.length>0);
	dpPanelFieldControls(field).forEach(function(input){
		input.setAttribute("aria-invalid",Array.isArray(errors)&&errors.length>0 ? "true" : "false");
	});
	if(!Array.isArray(errors)||!errors.length){return;}
	errors.forEach(function(message){
		var item=document.createElement("small");
		item.className="dp-panel-error";
		item.textContent=String(message||"");
		field.appendChild(item);
	});
}
/**
 * Applies server-provided help text to a field wrapper.
 *
 * Dynamic help reuses an existing static help element when available so layout
 * position stays stable across refreshes.
 *
 * @param {Element} field Field wrapper.
 * @param {Object<string, *>} state Reactive field state payload.
 * @returns {void}
 */
function dpPanelApplyFieldHelp(field,state){
	if(!("help" in state)){return;}
	var help=field.querySelector(":scope > .dp-panel-help[data-dp-panel-dynamic-help]");
	var staticHelp=field.querySelector(":scope > .dp-panel-help:not([data-dp-panel-dynamic-help])");
	if(!help&&staticHelp){help=staticHelp;help.dataset.dpPanelDynamicHelp="1";}
	var text=state.help===null||state.help===undefined ? "" : String(state.help);
	if(!text){
		if(help){help.remove();}
		return;
	}
	if(!help){
		help=document.createElement("small");
		help.className="dp-panel-help";
		help.dataset.dpPanelDynamicHelp="1";
		var firstError=field.querySelector(":scope > .dp-panel-error");
		field.insertBefore(help,firstError||null);
	}
	help.textContent=text;
}
/**
 * Applies a server-provided placeholder to text-like controls in a field.
 *
 * @param {Element} field Field wrapper.
 * @param {Object<string, *>} state Reactive field state payload.
 * @returns {void}
 */
function dpPanelApplyFieldPlaceholder(field,state){
	if(!("placeholder" in state)){return;}
	var value=state.placeholder===null||state.placeholder===undefined ? "" : String(state.placeholder);
	dpPanelFieldControls(field).forEach(function(input){
		if(input.type==="hidden"||input.type==="checkbox"||input.type==="radio"||input.tagName==="SELECT"){return;}
		if(value===""){input.removeAttribute("placeholder");}
		else{input.setAttribute("placeholder",value);}
	});
}
/**
 * Applies a server-authoritative value to field controls when allowed.
 *
 * Focused editable controls are not overwritten unless `force_value` is true,
 * protecting in-progress typing while still allowing state callbacks to update
 * hidden, checkbox, radio, select, and unfocused controls.
 *
 * @param {Element} field Field wrapper.
 * @param {Object<string, *>} state Reactive field state payload.
 * @returns {void}
 */
function dpPanelApplyFieldValue(field,state){
	if(state.value_from_server!==true||!("value" in state)){return;}
	var controls=dpPanelFieldControls(field);
	if(!controls.length){return;}
	var active=document.activeElement;
	if(state.force_value!==true&&active&&field.contains(active)&&!active.readOnly&&active.type!=="hidden"){
		return;
	}
	var value=String(state.value===null||state.value===undefined ? "" : state.value);
	var changed=false;
	controls.forEach(function(input){
		if(input.type==="hidden"){return;}
		if(input.type==="checkbox"){
			var checked=value==="1"||value==="true"||value===input.value;
			if(input.checked!==checked){input.checked=checked;changed=true;}
			return;
		}
		if(input.type==="radio"){
			var next=input.value===value;
			if(input.checked!==next){input.checked=next;changed=true;}
			return;
		}
		if(input.tagName==="SELECT"){
			var hasOption=Array.prototype.some.call(input.options,function(option){return option.value===value;});
			if(hasOption&&input.value!==value){input.value=value;changed=true;}
			return;
		}
		if(input.value!==value){input.value=value;changed=true;}
	});
	if(changed&&state.propagate===true){
		controls.forEach(function(input){input.dispatchEvent(new Event("change",{bubbles:true}));});
	}
}
/**
 * Applies a complete server reactive-state payload to one field.
 *
 * The mutation covers visibility, required and readonly flags, dynamic options,
 * server-provided values, help, placeholders, validation errors, and freshness
 * metadata. The payload is trusted only for this rendered form instance.
 *
 * @param {HTMLFormElement} form Panel form that owns the field.
 * @param {Element} field Field wrapper to mutate.
 * @param {Object<string, *>} state Server reactive-state payload for the field.
 * @param {boolean} applyErrors Whether validation errors should be rendered.
 * @returns {void}
 */
function dpPanelApplyFieldState(form,field,state,applyErrors){
	if(!field||!state){return;}
	var visible=state.visible!==false;
	var required=state.required===true;
	var readonly=state.readonly===true;
	field.classList.toggle("dp-panel-field-hidden",!visible);
	field.classList.toggle("dp-panel-field-required",visible&&required);
	dpPanelFieldControls(field).forEach(function(input){
		input.disabled=!visible;
		dpPanelSetFieldControlRequired(input,visible&&required);
		if(input.tagName!=="SELECT"&&input.type!=="checkbox"&&input.type!=="radio"&&input.type!=="file"){input.readOnly=readonly;}
		input.setAttribute("aria-readonly",readonly ? "true" : "false");
	});
	if(state.dynamic_options===true&&typeof state.options_html==="string"){
		var fieldName=field.dataset.dpPanelFieldName||state.name||"";
		var select=fieldName!=="" ? field.querySelector("select[name='"+dpPanelCssEscape(fieldName)+"']") : field.querySelector("select");
		if(select){
			var previous=select.value;
			select.innerHTML=state.options_html;
			if(Array.prototype.some.call(select.options,function(option){return option.value===previous;})){
				select.value=previous;
			}
			else if(state.value!==undefined&&Array.prototype.some.call(select.options,function(option){return option.value===String(state.value);})){
				select.value=String(state.value);
			}
		}
	}
	dpPanelApplyFieldValue(field,state);
	dpPanelApplyFieldHelp(field,state);
	dpPanelApplyFieldPlaceholder(field,state);
	if(applyErrors===true&&state.validated===true){
		dpPanelApplyFieldErrors(field,state.errors||[]);
	}
	field.dataset.dpPanelReactiveState="fresh";
}
/**
 * Requests server-side reactive state for fields affected by an input change.
 *
 * The request posts the full current form state, optionally asks the server to
 * validate the source field, and applies only payload entries returned for the
 * current form. Failures mark targets as errored without interrupting typing.
 *
 * @param {Element} input Source control that changed.
 * @param {boolean} validate Whether the refresh should include field validation.
 * @returns {void}
 */
function dpPanelRefreshReactiveState(input,validate){
	if(!window.fetch||!window.FormData){return;}
	var form=input.closest("form.dp-panel-form");
	if(!form){return;}
	var sourceName=dpPanelReactiveFieldName(input);
	var targets=dpPanelReactiveStateTargets(form,sourceName,validate===true);
	if(!targets.length){return;}
	var key="state_"+(sourceName||"_all");
	var sourceField=input.closest("[data-dp-panel-field-name]");
	var delay=validate===true ? 0 : parseInt((sourceField&&sourceField.dataset.dpPanelDebounceMs)||"120",10)||0;
	clearTimeout(dpPanelReactiveTimers[key]);
	dpPanelReactiveTimers[key]=setTimeout(function(){
		var body=new FormData(form);
		body.append("__panel_partial","field_state");
		if(validate===true){
			body.append("__panel_validate","field");
			body.append("__panel_validate_field",sourceName);
		}
		targets.forEach(function(field){field.classList.add("dp-panel-field-reactive-loading");});
		fetch(dpPanelReactiveUrl(form),{
			method:"POST",
			body:body,
			credentials:"same-origin",
			headers:{"Accept":"application/json","X-Requested-With":"DataphyrePanelFieldState"}
		}).then(function(response){
			if(!response.ok){throw new Error("field_state_failed");}
			return response.json();
		}).then(function(payload){
			var states=payload&&payload.fields ? payload.fields : {};
			var applyErrors=payload&&payload.validated===true;
			var applied={};
			targets.forEach(function(field){
				var fieldName=field.dataset.dpPanelFieldName||"";
				if(states[fieldName]){
					dpPanelApplyFieldState(form,field,states[fieldName],applyErrors);
					applied[fieldName]=true;
				}
			});
			Object.keys(states).forEach(function(fieldName){
				if(applied[fieldName]){return;}
				var state=states[fieldName]||{};
				if(state.value_from_server!==true&&state.state_updates!==true&&state.dynamic_options!==true){return;}
				var field=form.querySelector("[data-dp-panel-field-name='"+dpPanelCssEscape(fieldName)+"']");
				if(field){dpPanelApplyFieldState(form,field,state,applyErrors);}
			});
			if(typeof dpPanelRefreshPanelUi==="function"){dpPanelRefreshPanelUi();}
		}).catch(function(){
			targets.forEach(function(field){field.dataset.dpPanelReactiveState="error";});
		}).finally(function(){
			targets.forEach(function(field){field.classList.remove("dp-panel-field-reactive-loading");});
		});
	},delay);
}
