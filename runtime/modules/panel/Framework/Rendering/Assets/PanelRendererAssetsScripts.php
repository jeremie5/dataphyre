var dpPanelLastSelectionInput=null;
dpPanelListen(document,"click",function(event){
	var input=event.target.closest("input[name='selected[]']");
	if(!input){return;}
	var table=input.closest("table");
	if(event.shiftKey&&dpPanelLastSelectionInput&&table&&dpPanelLastSelectionInput.closest("table")===table){
