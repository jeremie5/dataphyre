/**
 * Extracts display text from a notification payload.
 *
 * @param {string|Object<string, *>|null} notification Notification object or raw text.
 * @returns {string} Human-facing notification text.
 */
function dpPanelNotificationText(notification){
	if(!notification){return "";}
	if(typeof notification==="string"){return notification;}
	var title=notification.title?String(notification.title):"";
	var message=notification.message?String(notification.message):"";
	return title&&message ? title+": "+message : (message||title);
}
/**
 * Renders a transient or persistent Panel toast notification.
 *
 * Notification objects may provide type, tone, icon, title, message, action URL,
 * action label, duration, and persistence metadata. Text is escaped before it is
 * inserted into generated markup.
 *
 * @param {string|Object<string, *>} notification Notification payload or text.
 * @param {string} tone Fallback tone for raw text notifications.
 * @returns {void}
 */
function dpPanelToast(notification,tone){
	var object=notification&&typeof notification==="object"&&!Array.isArray(notification) ? notification : null;
	var message=object ? dpPanelNotificationText(object) : String(notification||"");
	if(!message){return;}
	var root=dpPanelToastRoot();
	var toast=document.createElement("div");
	var type=String((object?(object.type||object.tone):tone)||"info").toLowerCase().replace(/[^a-z_]/g,"")||"info";
	toast.className="dp-panel-toast dp-panel-toast-"+type;
	var icon=object&&object.icon?String(object.icon):type.slice(0,2).toUpperCase();
	var title=object&&object.title?String(object.title):"";
	var body=object&&object.message?String(object.message):message;
	var actionUrl=object&&(object.action_url||object.url)?String(object.action_url||object.url):"";
	var actionLabel=object&&object.action_label?String(object.action_label):"Open";
	var persistent=object&&object.persistent===true;
	var duration=object&&object.duration_ms!==undefined&&object.duration_ms!==null ? parseInt(object.duration_ms,10) : 4200;
	if(!isFinite(duration)){duration=4200;}
	var progress=!persistent&&duration>0 ? "<span class=\"dp-panel-toast-progress\" style=\"animation-duration:"+Math.max(1200,duration)+"ms\"></span>" : "";
	toast.innerHTML="<span class=\"dp-panel-toast-icon\" aria-hidden=\"true\">"+dpPanelEscape(icon)+"</span><span class=\"dp-panel-toast-copy\">"+(title?"<strong>"+dpPanelEscape(title)+"</strong>":"")+"<span>"+dpPanelEscape(body)+"</span></span>"+progress;
	if(actionUrl){
		var action=document.createElement("a");
		action.href=actionUrl;
		action.textContent=actionLabel;
		toast.appendChild(action);
	}
	var close=document.createElement("button");
	close.type="button";
	close.setAttribute("aria-label","Dismiss notification");
	close.innerHTML="&times;";
	close.addEventListener("click",function(){
		toast.classList.remove("show");
		setTimeout(function(){toast.remove();},220);
	});
	toast.appendChild(close);
	root.appendChild(toast);
	requestAnimationFrame(function(){toast.classList.add("show");});
	if(!persistent&&duration>0){
		setTimeout(function(){
			toast.classList.remove("show");
			setTimeout(function(){toast.remove();},220);
		},Math.max(1200,duration));
	}
}
