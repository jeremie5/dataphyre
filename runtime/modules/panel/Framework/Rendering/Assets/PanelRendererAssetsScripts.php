	if(actionGroupSummary&&actionGroupSummary.closest(".dp-panel")){
		event.preventDefault();
		event.stopImmediatePropagation();
		var actionGroup=actionGroupSummary.closest(".dp-panel-action-group");
		var openActionGroup=actionGroup&&!actionGroup.open;
		if(!actionGroup){return;}
		if(openActionGroup){
			actionGroup.open=true;
			dpPanelPrepareActionGroupMenu(actionGroup);
			dpPanelCloseTransientPanels(actionGroup);
		}
		else {
			actionGroup.removeAttribute("open");
			dpPanelPrepareActionGroupMenu(actionGroup);
		}
		return;
	}
	var openTransient=event.target.closest(".dp-panel-horizontal-group[open],.dp-panel-row-more[open],.dp-panel-column-picker[open],.dp-panel-action-group[open],.dp-panel-saved-view-menu[open]");
	if(openTransient){return;}
	dpPanelCloseTransientPanels(null);
