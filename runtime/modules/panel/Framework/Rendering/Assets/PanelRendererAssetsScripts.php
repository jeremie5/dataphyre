namespace Dataphyre\Panel;

/**
 * Emits the browser runtime script used by generated Panel pages.
 *
 * The script coordinates client-side panel interactions that are configured by
 * server-rendered DOM attributes and JSON payloads.
 */
trait PanelRendererAssetsScripts {
	/**
	 * Returns the browser runtime script for generated Panel interactions.
	 *
	 * The script manages localization lookup, live refresh, partial rendering,
	 * modal flows, command palette behavior, table affordances, uploads, and other
	 * client-side state transitions. Dynamic data is supplied through generated DOM
	 * attributes and JSON script tags rather than interpolated into this string.
	 *
	 * @return string JavaScript source emitted into the panel asset bundle.
	 */
	private static function script(): string {
		return <<<'JS'
var dpPanelLocalizationCache=null;
/**
 * Loads the generated Panel localization payload once for the browser runtime.
 *
 * The payload is read from the server-rendered JSON script tag and cached for
 * the lifetime of the page. Malformed or missing JSON fails closed to an empty
 * translation map so generated UI controls can continue operating.
 *
 * @returns {{translations: Object}} Localization state keyed by translation id.
 */
function dpPanelLocalization(){
	if(dpPanelLocalizationCache){return dpPanelLocalizationCache;}
	var node=document.querySelector("script[data-dp-panel-localization]");
	if(!node){
		dpPanelLocalizationCache={translations:{}};
		return dpPanelLocalizationCache;
	}
	try{
		dpPanelLocalizationCache=JSON.parse(node.textContent||"{}")||{};
	}catch(error){
		dpPanelLocalizationCache={translations:{}};
	}
	if(!dpPanelLocalizationCache.translations||typeof dpPanelLocalizationCache.translations!=="object"){
		dpPanelLocalizationCache.translations={};
	}
	return dpPanelLocalizationCache;
}
/**
 * Resolves a localized Panel string and applies token replacement.
 *
 * Tokens support both `{name}` and `:name` placeholders because server-rendered
 * strings and legacy client snippets use both forms. Missing translations fall
 * back to the supplied fallback or the key itself.
 *
 * @param {string} key Translation identifier.
 * @param {string} fallback Default text when no translation is registered.
 * @param {Object<string, *>} tokens Replacement values for placeholders.
 * @returns {string} Localized text safe for textContent assignment.
 */
function dpPanelText(key,fallback,tokens){
	var translations=dpPanelLocalization().translations||{};
	var value=Object.prototype.hasOwnProperty.call(translations,key) ? translations[key] : fallback;
	value=String(value===undefined||value===null ? key : value);
	if(tokens&&typeof tokens==="object"){
		Object.keys(tokens).forEach(function(token){
			var replacement=String(tokens[token]===undefined||tokens[token]===null ? "" : tokens[token]);
			value=value.split("{"+token+"}").join(replacement).split(":"+token).join(replacement);
		});
	}
	return value;
}
/**
 * Reads the current submitted value for a field name.
 *
 * Checkbox and radio groups are reduced to the checked value, while other
 * controls return the first matching control value. This mirrors the dependency
 * resolver used by server-side field visibility and required-state checks.
 *
 * @param {string} name Form control name to read.
 * @returns {string} Current value or an empty string when no value is selected.
 */
function dpPanelFieldValue(name){
	var inputs=document.querySelectorAll("[name=\""+name+"\"]");
	if(!inputs.length){return "";}
	var first=inputs[0];
	if(first.type==="checkbox"){
		for(var index=0;index<inputs.length;index++){
			if(inputs[index].checked){return inputs[index].value||"1";}
		}
		return "";
	}
	if(first.type==="radio"){
		for(var radio=0;radio<inputs.length;radio++){
			if(inputs[radio].checked){return inputs[radio].value||"";}
		}
		return "";
	}
	return first.value||"";
}
/**
 * Parses a dependency condition payload from a data attribute.
 *
 * Invalid JSON is ignored rather than surfaced to users because the dependency
 * payload is generated by the server and should not break unrelated controls.
 *
 * @param {string} value JSON dependency map.
 * @returns {Object<string, *>} Parsed dependency map.
 */
function dpPanelParseDependency(value){
	if(!value){return {};}
	try{return JSON.parse(value)||{};}catch(error){return {};}
}
