 * clipping on small screens.
 *
 * @param {HTMLDetailsElement} details Open horizontal menu details element.
 * @returns {void}
 */
function dpPanelPlaceHorizontalMenu(details){
	if(!details||!details.open){return;}
	var summary=details.querySelector(":scope>summary");
	var menu=details.querySelector(":scope>div");
	if(!summary||!menu){return;}
	var rect=summary.getBoundingClientRect();
	var anchor=details.closest(".dp-panel-horizontal-nav");
	var anchorRect=anchor ? anchor.getBoundingClientRect() : {left:0, top:0};
