function dpPanelSelectionScope(){
	var active=document.activeElement&&document.activeElement.closest ? document.activeElement.closest(".dp-panel-table-shell,.dp-panel-table") : null;
	if(active){return active;}
	var focused=document.querySelector(".dp-panel-row-focused");
	if(focused){return focused.closest(".dp-panel-table")||focused.closest(".dp-panel-table-shell")||document;}
	return document.querySelector(".dp-panel-table-shell")||document.querySelector(".dp-panel-bulk-form")||document;
}
/**
 * Resolves row-selection scope for a bulk action bar.
 *
 * Form-associated controls may live outside the table, so this helper can return
 * a query facade that limits checkbox reads to inputs bound to the same form id.
 *
 * @param {Element|null} bar Bulk action bar element.
 * @returns {Document|Element|Object} Scope object with `querySelectorAll`.
 */
function dpPanelSelectionScopeForBar(bar){
	if(!bar){return document;}
	var formId="";
	var action=bar.querySelector("[form]");
	if(action){formId=action.getAttribute("form")||"";}
	if(formId){
		return {
			querySelectorAll:function(selector){
				if(selector==="input[name='selected[]']"){
					return document.querySelectorAll("input[name='selected[]'][form='"+formId+"']");
				}
				return document.querySelectorAll(selector);
			}
		};
	}
	var previous=bar.previousElementSibling;
	while(previous){
		if(previous.matches&&previous.matches("[data-dp-panel-table-shell]")){return previous;}
		previous=previous.previousElementSibling;
	}
	return document;
}
