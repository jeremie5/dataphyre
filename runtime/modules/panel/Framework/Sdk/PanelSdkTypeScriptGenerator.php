function validateValue(value: unknown, schema: RuntimeSchema, path: string, mode: "request" | "response", depth = 0, budget: { count: number } = { count: 0 }): string[] {
  if (depth > 24 || ++budget.count > 20_000) return [`${path}: value exceeds validation bounds`];
  const anyOf = Array.isArray(schema.anyOf) ? schema.anyOf as RuntimeSchema[] : null;
  if (anyOf) return anyOf.some((member) => validateValue(value, member, path, mode, depth + 1, budget).length === 0) ? [] : [`${path}: union mismatch`];
  const type = typeof schema.type === "string" ? schema.type : null;
  if (type === null) return isJsonValue(value, new Set<object>(), 0, budget) ? [] : [`${path}: value is not bounded JSON`];
  if (!matchesType(value, type)) return [`${path}: expected ${type}`];
  const enumeration = Array.isArray(schema.enum) ? schema.enum : null;
  if (enumeration && !enumeration.some((item) => Object.is(item, value))) return [`${path}: enum mismatch`];
  const errors: string[] = [];
  if (type === "string") {
    const text = value as string;
    if (typeof schema.minLength === "number" && [...text].length < schema.minLength) errors.push(`${path}: shorter than minLength`);
    if (typeof schema.maxLength === "number" && [...text].length > schema.maxLength) errors.push(`${path}: longer than maxLength`);
    if (typeof schema.pattern === "string" && !(new RegExp(schema.pattern, "u")).test(text)) errors.push(`${path}: pattern mismatch`);
    if (typeof schema.format === "string" && !matchesFormat(text, schema.format)) errors.push(`${path}: format mismatch`);
  } else if (type === "number" || type === "integer") {
    const number = value as number;
    if (typeof schema.minimum === "number" && number < schema.minimum) errors.push(`${path}: below minimum`);
    if (typeof schema.maximum === "number" && number > schema.maximum) errors.push(`${path}: above maximum`);
  } else if (type === "array") {
    const items = value as unknown[];
    if (typeof schema.minItems === "number" && items.length < schema.minItems) errors.push(`${path}: fewer than minItems`);
    if (typeof schema.maxItems === "number" && items.length > schema.maxItems) errors.push(`${path}: more than maxItems`);
    if (schema.uniqueItems === true) {
      const unique = new Set(items.map((item) => canonicalJson(item)));
      if (unique.size !== items.length) errors.push(`${path}: duplicate items rejected`);
    }
    const itemSchema = schema.items as RuntimeSchema;
    items.forEach((item, index) => errors.push(...validateValue(item, itemSchema, `${path}[${index}]`, mode, depth + 1, budget)));
  } else if (type === "object") {
    const object = value as Record<string, unknown>;
    const properties = isObject(schema.properties) ? schema.properties as Record<string, RuntimeSchema> : {};
    const required = Array.isArray(schema.required) ? schema.required.filter((item): item is string => typeof item === "string") : [];
    required.forEach((name) => { if (!(name in object)) errors.push(`${path}.${name}: required property missing`); });
    for (const [name, item] of Object.entries(object)) {
      if (properties[name]) errors.push(...validateValue(item, properties[name], `${path}.${name}`, mode, depth + 1, budget));
