const fetchTransport: PanelSdkTransport = async (request) => {
  if (typeof fetch !== "function") throw new PanelSdkError("No fetch implementation is available.", "transport_unavailable", 0, null, null);
  const response = await fetch(request.url, {
    method: request.method,
    headers: request.headers,
    ...(request.body === undefined ? {} : { body: JSON.stringify(request.body) }),
    credentials: "same-origin",
    redirect: "error",
    ...(request.signal ? { signal: request.signal } : {}),
  });
  const text = await response.text();
  let body: unknown = null;
  if (text !== "") {
    try { body = JSON.parse(text) as unknown; }
    catch { throw new PanelSdkError("Transport returned malformed JSON.", "response_json_invalid", response.status, response.headers.get("x-correlation-id"), text); }
  }
  return { status: response.status, body, headers: Object.fromEntries(response.headers.entries()) };
};

function normalizeBaseUrl(value: string): string {
  const trimmed = value.trim();
  if (trimmed === "") return "";
  let url: URL;
  try { url = new URL(trimmed); } catch { throw new TypeError("Panel SDK baseUrl must be an absolute HTTP(S) URL or empty for same-origin requests."); }
  if (!/^https?:$/.test(url.protocol) || url.username || url.password || url.search || url.hash) throw new TypeError("Panel SDK baseUrl must not contain credentials, query, or fragment data.");
  return url.toString().replace(/\/$/, "");
}

function normalizeHeaders(headers: Readonly<Record<string, string>>): Readonly<Record<string, string>> {
  const output: Record<string, string> = {};
  for (const [name, value] of Object.entries(headers)) {
    if (!/^[!#$%&'*+.^_`|~0-9A-Za-z-]+$/.test(name) || /[\r\n]/.test(value)) throw new TypeError("Panel SDK header is invalid.");
    output[name] = value;
  }
  return output;
}

function buildPath(template: string, values: Readonly<Record<string, unknown>>): string {
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (_token, name: string) => {
    const value = values[name];
    if (typeof value !== "string" && typeof value !== "number") throw new TypeError(`Missing path parameter ${name}.`);
    return encodeURIComponent(String(value));
  });
}

function appendQuery(path: string, values: Readonly<Record<string, unknown>>): string {
  const query = new URLSearchParams();
  for (const [name, value] of Object.entries(values)) {
    if (value === undefined || value === null || value === "") continue;
    const items = Array.isArray(value) ? value : [value];
    for (const item of items) query.append(name, typeof item === "object" && item !== null ? JSON.stringify(item) : String(item));
  }
  const encoded = query.toString();
  return encoded ? `${path}?${encoded}` : path;
}

function publicError(body: unknown): { code: string; message: string; correlationId: string | null } {
  const object = isObject(body) ? body : {};
